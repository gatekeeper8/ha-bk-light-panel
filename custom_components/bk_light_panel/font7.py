# Polish (and a few other) letters drawn as their base letter
_FOLD = str.maketrans("ĄĆĘŁŃÓŚŹŻąćęłńóśźżµ", "ACELNOSZZACELNOSZZU")
HEIGHT = 7
GAP = 1


def glyph(char: str) -> tuple[str, ...] | None:
    return GLYPHS.get(char.translate(_FOLD).upper())


def fits(text: str) -> bool:
    return all(glyph(c) is not None for c in text)


def width(text: str) -> int:
    if not text:
        return 0
    return sum(len((glyph(c) or GLYPHS["?"])[0]) for c in text) + GAP * (len(text) - 1)


def draw(pixels, text: str, x: int, y: int, color, clip: tuple[int, int] = (0, 64)) -> int:
    """Draw at (x, y); returns the x after the text."""
    for char in text:
        rows = glyph(char) or GLYPHS["?"]
        for ry, row in enumerate(rows):
            for rx, pixel in enumerate(row):
                if pixel == "#" and clip[0] <= x + rx < clip[1] and 0 <= y + ry < 16:
                    pixels[x + rx, y + ry] = color
        x += len(rows[0]) + GAP
    return x


def wrap(text: str, max_width: int) -> list[str]:
    """Word wrap; a word wider than max_width stays whole (caller decides)."""
    lines: list[str] = []
    line = ""
    for word in text.split():
        candidate = f"{line} {word}" if line else word
        if width(candidate) <= max_width or not line:
            line = candidate
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines
